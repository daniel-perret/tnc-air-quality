# Unique variants present in run outputs
run_variants <- str_sub(basename(all_dbs), -5, -4) %>% unique()


## ---- Block-wise conditional mean / SD / CV ----

# Computes probability-weighted mean, SD, and CV in one chunked pass, writing
# three separate single-layer rasters directly to disk. Avoids the full-size
# intermediate rasters (stack * probs, residuals, squares, etc.) that terra
# would otherwise spill to tempdir. NA handling matches the previous
# app(..., sum) approach: any NA layer in a pixel gives NA for that pixel.
write_conditional_stats <- function(
    metric_stack,  # SpatRaster, one layer per FL bin: per-stand FVS estimates
    fl_rast,       # SpatRaster, FL probabilities (same grid as metric_stack after windowing)
    file_mean,     # output path for the conditional mean raster (character)
    file_sd,       # output path for the conditional SD raster (character)
    file_cv        # output path for the conditional CV raster (character)
) {

  # Restrict metric stack to the FL raster extent without writing a copy
  terra::window(metric_stack) <- terra::ext(fl_rast)
  stopifnot(terra::compareGeom(metric_stack, fl_rast, stopOnError = FALSE))

  r_mean <- terra::rast(fl_rast, nlyrs = 1)
  r_sd   <- terra::rast(fl_rast, nlyrs = 1)
  r_cv   <- terra::rast(fl_rast, nlyrs = 1)

  b <- terra::writeStart(r_mean, file_mean, overwrite = TRUE)
  terra::writeStart(r_sd, file_sd, overwrite = TRUE)
  terra::writeStart(r_cv, file_cv, overwrite = TRUE)
  terra::readStart(metric_stack)
  terra::readStart(fl_rast)

  on.exit({
    terra::readStop(metric_stack)
    terra::readStop(fl_rast)
  }, add = TRUE)

  for (i in seq_len(b$n)) {
    m <- terra::readValues(metric_stack, row = b$row[i], nrows = b$nrows[i], mat = TRUE)
    p <- terra::readValues(fl_rast,      row = b$row[i], nrows = b$nrows[i], mat = TRUE)

    mu <- rowSums(m * p)
    s  <- sqrt(rowSums(p * (m - mu)^2))

    terra::writeValues(r_mean, mu,     b$row[i], b$nrows[i])
    terra::writeValues(r_sd,   s,      b$row[i], b$nrows[i])
    terra::writeValues(r_cv,   s / mu, b$row[i], b$nrows[i])
  }

  terra::writeStop(r_mean)
  terra::writeStop(r_sd)
  terra::writeStop(r_cv)

  invisible(NULL)
}


## ---- Per-variant processing function (to be parallelized) ----

process_variant_all_fls <- function(
    variant,             # FVS variant code, e.g. "PN" (character)
    all_dbs_input,       # paths to all FVS output databases in the run (character vector)
    tm_clip_dir_input,   # directory of pre-clipped TreeMap rasters (character)
    fl_clip_dir_input,   # directory of pre-clipped FL probability rasters (character)
    outpath_root_input,  # root output directory; a subfolder per variant is created (character)
    metrics_input        # metric column names to rasterize, e.g. c("BAkill", "PctBAkill") (character vector)
) {

  message("Processing variant: ", variant)

  terra::terraOptions(memmax = 6, progress = 0, parallel = FALSE)

  # Remove any terra temp files this worker created, even on error
  on.exit(terra::tmpFiles(remove = TRUE), add = TRUE)

  outpath <- file.path(outpath_root_input, variant)
  dir.create(outpath, showWarnings = FALSE)

  # Use pre-clipped TreeMap raster for this variant
  tm.clip.path <- file.path(tm_clip_dir_input, paste0("tm_ref_", variant, ".tif"))

  # Build reclass table from all FL databases for this variant
  variant_dbs <- all_dbs_input[str_detect(all_dbs_input, paste0("_", variant, "\\.db$"))]

  # Start from FVS_Cases so stands with no FVS_Mortality row get Bakill = 0
  reclass.long <- map_dfr(variant_dbs, function(
    db_path  # path to one FVS output SQLite database (character)
) {
    fl_val <- parse_number(basename(db_path))
    con    <- dbConnect(SQLite(), db_path)
    dat    <- dbGetQuery(con, "SELECT c.StandID,
                                      COALESCE(m.Bakill, 0) AS BAkill,
                                      CASE WHEN s.BA > 0
                                           THEN 100.0 * COALESCE(m.Bakill, 0) / s.BA
                                      END AS PctBAkill
                               FROM FVS_Cases c
                               LEFT JOIN FVS_Mortality m
                                 ON c.CaseID = m.CaseID
                                AND m.SpeciesFVS = 'ALL'
                                AND m.Year = 2020
                               LEFT JOIN FVS_Summary s
                                 ON c.CaseID = s.CaseID
                                AND s.Year = 2020")
    dbDisconnect(con)
    mutate(dat, FL = fl_val, StandID = as.integer(StandID))
  })

  fl_levels_present   <- sort(unique(reclass.long$FL))
  fl_colnames_present <- paste0("FL", fl_levels_present)

  # Load pre-cropped FL probability rasters for this variant
  fl.rast <- rast(file.path(fl_clip_dir_input, paste0("fl_clip_", variant, ".tif")))

  for (metric in metrics_input) {

    reclass.df <- reclass.long %>%
      select(StandID, FL, all_of(metric)) %>%
      pivot_wider(names_from   = FL,
                  values_from  = all_of(metric),
                  names_prefix = "FL") %>%
      select(StandID, all_of(fl_colnames_present))

    # Reclassify raster for each FL bin SEQUENTIALLY (no inner parallelization)
    metric_files <- file.path(outpath, paste0(metric, "_", fl_colnames_present, ".tif"))

    for (i in seq_along(fl_colnames_present)) {
      var <- fl_colnames_present[i]

      # NA values (stands with BA <= 0) are dropped; others = NA covers them
      reclass.mat <- reclass.df %>%
        select(from = StandID, to = all_of(var)) %>%
        filter(!is.na(to)) %>%
        as.matrix()

      # Write straight to the final file (no in-memory/temp copy)
      terra::classify(rast(tm.clip.path), reclass.mat, others = NA,
                      filename = metric_files[i], overwrite = TRUE)
      gc()
    }

    # Stack FL rasters (already in ascending FL order)
    metric_stack <- rast(metric_files)
    names(metric_stack) <- fl_colnames_present

    # Conditional mean, SD, and CV (NaN/Inf in CV where mean is 0),
    # each written to its own single-layer raster
    write_conditional_stats(
      metric_stack, fl.rast,
      file_mean = file.path(outpath, paste0("Conditional_mean_", metric, ".tif")),
      file_sd   = file.path(outpath, paste0("Conditional_sd_",   metric, ".tif")),
      file_cv   = file.path(outpath, paste0("Conditional_cv_",   metric, ".tif"))
    )

    rm(reclass.df, metric_stack)
    gc()
  }

  rm(reclass.long, fl.rast)
  gc()
  message("Variant ", variant, " complete.")

}


## ---- Parallel execution over variants ----

future::plan(future.callr::callr, workers = 5)
furrr::future_map(run_variants,
                  ~ process_variant_all_fls(.,
                                            all_dbs,
                                            tm_clip_dir,
                                            fl_clip_dir,
                                            outpath_root,
                                            metrics),
                  .progress = TRUE)
future::plan(sequential)

message("Wildfire Bakill rasterization complete.")
