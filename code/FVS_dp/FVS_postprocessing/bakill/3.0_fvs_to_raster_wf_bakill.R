#### 3.0_fvs_to_raster_wf_bakill.R
#### Associates wildfire FVS basal area killed with pixel locations via TreeMap imputation.
#### Two metrics: BAkill (ft2/ac) and PctBAkill (% of pre-fire basal area).
#### For each FVS variant: reclassifies the TMFM2020 raster using per-stand values
#### for each flame length bin, then computes the conditional expected value weighted
#### by FlamStat flame length probability rasters. Percent killed is computed per stand
#### first and then probability-weighted (not a ratio of weighted means).
#### Bakill is taken from the all-species ("ALL") rows of FVS_Mortality in the fire year (2020).
#### Stands with no FVS_Mortality row (no live tree mortality) are assigned Bakill = 0.
#### Pre-fire BA is FVS_Summary BA in 2020 (fire-year rows are pre-fire);
#### stands with BA <= 0 get PctBAkill = NA.
#### Parallelizes over variants (not FL bins) for full worker utilization.
#### Outputs: per-variant rasters in data/dp_FVS_postprocess/{wf_run_name}/{VARIANT}/
#### (names include the metric so they do not collide with emissions rasters)
#### Variant rasters are mosaicked into CONUS layers in 3.2_variant_rasters_merge.R


