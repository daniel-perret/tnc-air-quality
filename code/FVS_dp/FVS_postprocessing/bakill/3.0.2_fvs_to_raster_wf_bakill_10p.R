#### 3.0.2_fvs_to_raster_wf_bakill_10p.R
#### Wildfire FVS basal area killed (BAkill, PctBAkill) from the lowest 10% of flame
#### length probabilities (excluding highest 90%). Reuses the per-FL metric rasters
#### written by 3.0_fvs_to_raster_wf_bakill.R.
#### Parallelizes over variants (not FL bins) for full worker utilization.
#### Outputs: per-variant rasters in data/dp_FVS_postprocess/{wf_run_name}_10p/{VARIANT}/
#### Variant rasters are mosaicked into CONUS layers in 3.2_variant_rasters_merge.R


## ---- Configuration ----

library(here)
source(here("code/FVS_dp/FVS_workflow/0.0_setup.R"))

# Completed wildfire wet run to rasterize (3.0 must already be run for this run)
wf_run_name <- "Wildfire_WetRun_21May26_0855"

# Pre-clipped FL rasters directory (generated by 0.3_fl_clip.R)
fl_clip_dir <- here("data/fl_clip_rasters")

# Metrics to process (must match 3.0)
metrics <- c("BAkill", "PctBAkill")

# Tail definition: probability mass taken from the lowest-FL end
tail_prob <- 0.10


## ---- Setup ----

all_dbs <- list.files(here("FVS_runs/full", wf_run_name, "outputs"), full.names = TRUE)

source_root  <- here("data/dp_FVS_postprocess", wf_run_name)
outpath_root <- here("data/dp_FVS_postprocess", paste0(wf_run_name, "_10p"))
dir.create(outpath_root, showWarnings = FALSE)

# Unique variants present in run outputs
run_variants <- str_sub(basename(all_dbs), -5, -4) %>% unique()


## ---- Per-variant processing function (to be parallelized) ----

process_variant_10p <- function(variant, fl_clip_dir_input, source_root_input,
                                outpath_root_input, metrics_input, tail_prob_input) {

  message("Processing variant: ", variant)

  terra::terraOptions(memmax = 6, progress = 0, parallel = FALSE)

  outpath        <- file.path(outpath_root_input, variant)
  source_outpath <- file.path(source_root_input, variant)
  dir.create(outpath, showWarnings = FALSE)

  # Load pre-cropped FL probability rasters for this variant
  fl.rast <- terra::rast(file.path(fl_clip_dir_input, paste0("fl_clip_", variant, ".tif")))

  for (metric in metrics_input) {

    # Intermediate per-FL rasters created by 3.0 (reused instead of regenerated)
    fl_files <- list.files(source_outpath,
                           pattern = paste0("^", metric, "_FL[0-9]+\\.tif$"),
                           full.names = TRUE)

    if (length(fl_files) == 0) {
      stop("No ", metric, "_FL*.tif rasters found in 3.0 output directory: ", source_outpath,
           "\nEnsure 3.0_fvs_to_raster_wf_bakill.R has been run before 3.0.2")
    }

    # Sort FL values numerically (ascending FL)
    fl_values <- as.numeric(str_extract(basename(fl_files), "(?<=FL)\\d+"))
    fl_colnames_present <- paste0("FL", sort(fl_values))

    metric_stack <- terra::rast(file.path(source_outpath,
                                          paste0(metric, "_", fl_colnames_present, ".tif")))

    # Align extents
    metric_stack <- terra::crop(metric_stack, fl.rast)

    # Probability-weighted mean from the lowest 10% of FL probabilities.
    # For each pixel: accumulate probability from the lowest FL bin upward until
    # tail_prob is reached, partially weight the boundary bin, renormalize to sum to 1.
    tail.mean <- app(
      c(fl.rast, metric_stack),
      \(x) {
        n_fl   <- length(x) / 2
        probs  <- x[1:n_fl]
        values <- x[(n_fl + 1):(2 * n_fl)]

        cum_prob      <- 0
        threshold_idx <- NA_integer_
        partial_prob  <- NA_real_

        for (i in 1:n_fl) {
          if (is.na(probs[i])) next

          prob_before <- cum_prob
          cum_prob    <- cum_prob + probs[i]

          if (cum_prob >= tail_prob_input) {
            threshold_idx <- i
            partial_prob  <- min(tail_prob_input - prob_before, probs[i])
            break
          }
        }

        if (is.na(threshold_idx)) return(NA_real_)

        probs_reweighted <- numeric(n_fl)
        if (threshold_idx > 1) {
          probs_reweighted[1:(threshold_idx - 1)] <- probs[1:(threshold_idx - 1)]
        }
        probs_reweighted[threshold_idx] <- partial_prob

        prob_sum <- sum(probs_reweighted, na.rm = TRUE)
        if (prob_sum == 0 || is.na(prob_sum)) return(NA_real_)
        probs_reweighted <- probs_reweighted / prob_sum

        # na.rm = FALSE propagates NAs
        sum(values * probs_reweighted, na.rm = FALSE)
      }
    )

    terra::writeRaster(tail.mean,
                       file.path(outpath, paste0("bottom10pct_mean_", metric, ".tif")),
                       overwrite = TRUE)

    rm(metric_stack, tail.mean)
    gc()
  }

  rm(fl.rast)
  gc()
  message("Variant ", variant, " complete.")

}


## ---- Parallel execution over variants ----

future::plan(future.callr::callr, workers = 10)
furrr::future_map(run_variants,
                  ~ process_variant_10p(.,
                                        fl_clip_dir,
                                        source_root,
                                        outpath_root,
                                        metrics,
                                        tail_prob),
                  .progress = TRUE)
future::plan(sequential)

message("Wildfire bottom-10% Bakill rasterization complete.")
